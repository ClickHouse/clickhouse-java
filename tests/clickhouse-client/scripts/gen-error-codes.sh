#!/usr/bin/env bash
# Generates the error code table of the shim
# (src/main/resources/com/clickhouse/client/cli/error-codes.tsv) from
# src/Common/ErrorCodes.cpp of a ClickHouse checkout. fetch-upstream.sh runs
# it after each checkout, so the error names of the test hints always match
# the tests. It needs only bash and sed. Commit the file when it changes.
#
# Usage: scripts/gen-error-codes.sh [<ClickHouse checkout>]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUNNER_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
checkout="${1:-${UPSTREAM_CLICKHOUSE_DIR:-${RUNNER_DIR}/.upstream/ClickHouse}}"
src_file="${checkout}/src/Common/ErrorCodes.cpp"

if [[ ! -f "${src_file}" ]]; then
  echo "Error: ${src_file} not found. Run scripts/fetch-upstream.sh first." >&2
  exit 1
fi
ref="$(cat "${checkout}/.upstream-ref" 2>/dev/null || git -C "${checkout}" rev-parse HEAD)"

out="${RUNNER_DIR}/src/main/resources/com/clickhouse/client/cli/error-codes.tsv"
mkdir -p "$(dirname "${out}")"
{
  echo "# Generated by scripts/gen-error-codes.sh from src/Common/ErrorCodes.cpp of ClickHouse ${ref}; do not edit."
  echo "# <code><TAB><name>: test hints can name an error instead of giving its code."
  sed -n 's/^ *M(\([0-9][0-9]*\), *\([A-Z0-9_][A-Z0-9_]*\)).*/\1\t\2/p' "${src_file}"
} > "${out}"
echo "Wrote $(grep -vc '^#' "${out}") error codes from ${ref} to ${out}" >&2
